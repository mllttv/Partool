use std::{env, fs, path::Path};

fn collect_routes(
    dir: &Path,
    base: &Path,
    prefix: &str,
    routes: &mut Vec<(String, String, String)>,
) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_routes(&path, base, prefix, routes);
        } else if path.extension().is_some_and(|e| e == "rs") {
            let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or("");
            if stem != "mod" && !stem.starts_with(['_', '.']) {
                if let Ok(rel) = path.strip_prefix(base) {
                    let rel_str = rel.to_string_lossy().replace('\\', "/");
                    let route_path = if prefix.is_empty() {
                        format!("/{}", rel_str)
                    } else {
                        format!("{}/{}", prefix.trim_end_matches('/'), rel_str)
                    };
                    let mod_name = format!(
                        "route_{}",
                        route_path.trim_start_matches('/').replace(['/', '.', '-'], "_")
                    );
                    routes.push((
                        mod_name,
                        route_path,
                        path.canonicalize().unwrap_or(path).to_string_lossy().into(),
                    ));
                }
            }
        }
    }
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/routes");
    println!("cargo:rerun-if-changed=src/components/account");

    let out_dir = env::var("OUT_DIR").unwrap();
    let routes_dir = Path::new("src/routes");
    let account_dir = Path::new("src/components/account");

    let mut routes = Vec::new();
    // 1. Standard dynamic routes: https://domain/path/to/file.rs -> ./src/routes/path/to/file.rs
    collect_routes(routes_dir, routes_dir, "", &mut routes);

    // 2. Explicitly whitelist account routes: https://domain/account/path/to/file.rs -> ./src/components/account/path/to/file.rs
    // Security: Only src/components/account is scanned. Never expose components/ as a whole.
    collect_routes(account_dir, account_dir, "/account", &mut routes);

    routes.sort_by(|a, b| a.1.cmp(&b.1));

    let mut code = String::from("// Auto-generated by build.rs - DO NOT EDIT MANUALLY\n\n");
    for (mod_name, _, abs_path) in &routes {
        code.push_str(&format!("#[path = \"{abs_path}\"]\npub mod {mod_name};\n"));
    }

    code.push_str("\npub fn build_dynamic_router() -> axum::Router {\n    axum::Router::new()\n");
    for (mod_name, route_path, _) in &routes {
        code.push_str(&format!(
            "        .nest(\"{route_path}\", {mod_name}::router())\n"
        ));
    }
    code.push_str("}\n\npub fn get_available_routes() -> &'static [&'static str] {\n    &[\n");
    for (_, route_path, _) in &routes {
        code.push_str(&format!("        \"{route_path}\",\n"));
    }
    code.push_str("    ]\n}\n");

    fs::write(Path::new(&out_dir).join("dynamic_routes.rs"), code).unwrap();
}
